    /// Snapshot test: golden output for the hello-stack fixture.
    /// Update via `UPDATE_SNAPSHOT=1 cargo test compose_snapshot`.
    #[test]
    fn compose_snapshot_matches_golden() {
        let inspect = full_fixture();
        let yaml = build_compose("hello", &[inspect], None).unwrap();

        let golden_path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("tests")
            .join("fixtures")
            .join("hello-stack.compose.golden.yaml");
        if std::env::var("UPDATE_SNAPSHOT").is_ok() {
            std::fs::write(&golden_path, &yaml).expect("write golden");
            return;
        }
        let golden = std::fs::read_to_string(&golden_path).unwrap_or_default();
        assert_eq!(
            yaml.trim_end(),
            golden.trim_end(),
            "snapshot drift; rerun with UPDATE_SNAPSHOT=1 to refresh"
        );
    }


    #[test]
    fn maps_image_into_compose_image_key() {
        let mut inspect = empty_inspect();
        inspect.config = Some(ContainerConfig {
            image: Some("nginxdemos/hello:plain-text".into()),
            ..Default::default()
        });
        let yaml = build_compose("hello", &[inspect], None).unwrap();
        assert!(yaml.contains("image: nginxdemos/hello:plain-text"));
    }

    #[test]
    fn maps_cmd_and_entrypoint() {
        let mut inspect = empty_inspect();
        inspect.config = Some(ContainerConfig {
            cmd: Some(vec!["nginx".into(), "-g".into(), "daemon off;".into()]),
            entrypoint: Some(vec!["/docker-entrypoint.sh".into()]),
            ..Default::default()
        });
        let yaml = build_compose("hello", &[inspect], None).unwrap();
        // entrypoint emitted before command (insertion order from build_service).
        assert!(yaml.contains("entrypoint:"));
        assert!(yaml.contains("/docker-entrypoint.sh"));
        assert!(yaml.contains("command:"));
        assert!(yaml.contains("daemon off;"));
    }

